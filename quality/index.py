"""Deterministic references from local docs, skills and the real CLI tree."""

from __future__ import annotations

import difflib
import json
from pathlib import Path
from typing import Any

import typer.main
import yaml

from changecost.cli import app


def render(root: Path) -> dict[str, str]:
    entries = json.loads((root / "quality/index.json").read_text())
    seen: set[str] = set()
    lines = [
        "# ChangeCost",
        "",
        "> Private, unreleased 0.x offline contracts, lifecycle and normalized settlement CLI. "
        "Provider operations remain planned.",
        "",
        "## Project and evidence",
        "",
    ]
    for entry in entries:
        path = entry["path"]
        if path in seen or not (root / path).is_file():
            raise ValueError(f"duplicate or dangling index entry: {path}")
        seen.add(path)
        lines.append(f"- [{entry['title']}]({path}): {entry['description']}")
    lines += ["", "## Local skills", ""]
    skills: set[str] = set()
    for path in sorted((root / ".agents/skills").glob("*/SKILL.md")):
        header = yaml.safe_load(path.read_text().split("---", 2)[1])
        name = header["name"]
        if name in skills:
            raise ValueError(f"duplicate skill: {name}")
        skills.add(name)
        description = " ".join(header["description"].split())
        lines.append(f"- [{name}]({path.relative_to(root).as_posix()}): {description}")
    command = typer.main.get_command(app)
    reference = [
        "# CLI reference",
        "",
        "<!-- Generated by python -m quality index --write. -->",
        "",
        "Implemented command surface:",
        "",
    ]
    reference += command_lines(command, "changecost")
    reference += [
        "",
        "Help and version succeed offline. Bare or unknown commands exit nonzero.",
        "No database, configuration or evidence files are created by these invocations.",
        "",
        "`bind` registers/maps/imports; `settle` declares lifecycle, "
        "imports normalized evidence or computes;",
        "`explain` inspects/exports and reports repository remainder. "
        "`quote` computes offline empirical estimates. "
        "`check` and provider adapters remain planned.",
        "",
    ]
    lines += [
        "",
        "## Implemented CLI",
        "",
        "- [CLI reference](docs/commands.md): generated from the installed command definition.",
        "",
    ]
    return {"llms.txt": "\n".join(lines), "docs/commands.md": "\n".join(reference)}


def check_outputs(root: Path, outputs: dict[str, str]) -> list[str]:
    errors: list[str] = []
    for name, expected in outputs.items():
        path = root / name
        actual = path.read_text() if path.exists() else ""
        if actual != expected:
            diff = "".join(
                difflib.unified_diff(
                    actual.splitlines(True),
                    expected.splitlines(True),
                    fromfile=name,
                    tofile="generated",
                )
            )
            errors.append(f"stale/missing generated output: {name}; run make generate\n{diff}")
    return errors


def command_lines(command: Any, prefix: str) -> list[str]:
    """Walk the actual registered tree, including command-specific options."""
    options = sorted({option for param in command.params for option in param.opts} | {"--help"})
    lines = [f"- `{prefix} {option}`" for option in options]
    for name, child in sorted(getattr(command, "commands", {}).items()):
        lines.append(f"- `{prefix} {name}`")
        lines.extend(command_lines(child, f"{prefix} {name}"))
    return lines
